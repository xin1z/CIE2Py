std::string CodeGenerator::pythonName(const std::string& name)
{
  const std::string key = toLower(name);
  const auto existing = names_.find(key);
  if (existing != names_.end())
    return existing->second;

  std::string candidate = name;
  while (isReservedName(candidate) || usedNames_.contains(candidate))
    candidate += '_';

  names_.emplace(key, candidate);
  usedNames_.insert(candidate);
  return candidate;
}

std::string CodeGenerator::freshName(const std::string& prefix)
{
  std::string candidate;
  do
  {
    candidate = prefix + std::to_string(tempCounter_++);
  } while (usedNames_.contains(candidate));

  usedNames_.insert(candidate);
  return candidate;
}

void CodeGenerator::pushScope()
{
  scopes_.emplace_back();
}

void CodeGenerator::popScope()
{
  scopes_.pop_back();
}

void CodeGenerator::declare(const std::string& name, Symbol symbol)
{
  scopes_.back()[toLower(name)] = std::move(symbol);
}

const CodeGenerator::Symbol* CodeGenerator::lookup(const std::string& name) const
{
  const std::string key = toLower(name);
  for (auto scope = scopes_.rbegin(); scope != scopes_.rend(); ++scope)
  {
    const auto found = scope->find(key);
    if (found != scope->end())
      return &found->second;
  }

  return nullptr;
}

