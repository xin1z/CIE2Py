void CodeGenerator::generateStatements(const std::vector<StmtPtr>& statements)
{
  for (std::size_t i = 0; i < statements.size(); ++i)
  {
    generateStatement(*statements[i]);

    const bool subprogram = statements[i]->kind == NodeKind::PROCEDURE_DECLARATION ||
                            statements[i]->kind == NodeKind::FUNCTION_DECLARATION;
    if (indent_ == 0 && subprogram && i + 1 < statements.size())
      blankLine();
  }
}

// Collect module-level declarations before generating any subprogram. This
// keeps the global-variable analysis independent of source order: the parser
// does not reject a declaration that appears after a procedure or function.
void CodeGenerator::prescanGlobals(const std::vector<StmtPtr>& statements)
{
  for (const StmtPtr& statementPtr : statements)
  {
    const Stmt& statement = *statementPtr;
    switch (statement.kind)
    {
    case NodeKind::VARIABLE_DECLARATION:
    {
      const auto& declaration = static_cast<const VariableDeclarationStmt&>(statement);
      pythonName(declaration.name);
      Symbol symbol;
      symbol.type = declaration.type;
      declare(declaration.name, std::move(symbol));
      break;
    }
    case NodeKind::CONSTANT_DECLARATION:
    {
      const auto& declaration = static_cast<const ConstantDeclarationStmt&>(statement);
      pythonName(declaration.name);
      declare(declaration.name, Symbol{});
      break;
    }
    case NodeKind::ARRAY_DECLARATION:
    {
      const auto& declaration = static_cast<const ArrayDeclarationStmt&>(statement);
      const std::string name = pythonName(declaration.name);

      Symbol symbol;
      symbol.type = declaration.elementType;
      symbol.isArray = true;

      PendingArray pending;
      pending.lowerCaptures.resize(declaration.dimensions.size());

      for (std::size_t i = 0; i < declaration.dimensions.size(); ++i)
      {
        const ArrayDimension& dimension = declaration.dimensions[i];
        ArrayBound bound;
        bound.expression = dimension.lower.get();

        std::int64_t lowerValue = 0;
        if (!foldInteger(*dimension.lower, lowerValue))
        {
          bound.capture = freshName("_cie_lower_" + name + "_");
          pending.lowerCaptures[i] = bound.capture;
        }

        symbol.lowerBounds.push_back(std::move(bound));
      }

      pendingArrays_[&declaration] = std::move(pending);
      declare(declaration.name, std::move(symbol));
      break;
    }
    case NodeKind::IF:
      prescanGlobals(static_cast<const IfStmt&>(statement).thenBody);
      prescanGlobals(static_cast<const IfStmt&>(statement).elseBody);
      break;
    case NodeKind::CASE:
    {
      const auto& caseStatement = static_cast<const CaseStmt&>(statement);
      for (const CaseClause& clause : caseStatement.clauses)
        prescanGlobals(clause.body);
      prescanGlobals(caseStatement.otherwiseBody);
      break;
    }
    case NodeKind::FOR:
      prescanGlobals(static_cast<const ForStmt&>(statement).body);
      break;
    case NodeKind::WHILE:
      prescanGlobals(static_cast<const WhileStmt&>(statement).body);
      break;
    case NodeKind::REPEAT:
      prescanGlobals(static_cast<const RepeatStmt&>(statement).body);
      break;
    default:
      break;
    }
  }
}

void CodeGenerator::generateBlock(const std::vector<StmtPtr>& statements)
{
  ++indent_;
  if (statements.empty())
    line("pass");
  else
    generateStatements(statements);
  --indent_;
}

void CodeGenerator::generateStatement(const Stmt& statement)
{
  switch (statement.kind)
  {
  case NodeKind::VARIABLE_DECLARATION:
    generateVariableDeclaration(static_cast<const VariableDeclarationStmt&>(statement));
    break;
  case NodeKind::CONSTANT_DECLARATION:
    generateConstantDeclaration(static_cast<const ConstantDeclarationStmt&>(statement));
    break;
  case NodeKind::ARRAY_DECLARATION:
    generateArrayDeclaration(static_cast<const ArrayDeclarationStmt&>(statement));
    break;
  case NodeKind::ASSIGNMENT:
    generateAssignment(static_cast<const AssignmentStmt&>(statement));
    break;
  case NodeKind::INPUT:
    generateInput(static_cast<const InputStmt&>(statement));
    break;
  case NodeKind::OUTPUT:
    generateOutput(static_cast<const OutputStmt&>(statement));
    break;
  case NodeKind::IF:
    generateIf(static_cast<const IfStmt&>(statement));
    break;
  case NodeKind::CASE:
    generateCase(static_cast<const CaseStmt&>(statement));
    break;
  case NodeKind::FOR:
    generateFor(static_cast<const ForStmt&>(statement));
    break;
  case NodeKind::WHILE:
    generateWhile(static_cast<const WhileStmt&>(statement));
    break;
  case NodeKind::REPEAT:
    generateRepeat(static_cast<const RepeatStmt&>(statement));
    break;
  case NodeKind::PROCEDURE_DECLARATION:
    generateProcedure(static_cast<const ProcedureDeclarationStmt&>(statement));
    break;
  case NodeKind::FUNCTION_DECLARATION:
    generateFunction(static_cast<const FunctionDeclarationStmt&>(statement));
    break;
  case NodeKind::CALL:
    generateCall(static_cast<const CallStmt&>(statement));
    break;
  case NodeKind::RETURN:
    generateReturn(static_cast<const ReturnStmt&>(statement));
    break;
  case NodeKind::OPEN_FILE:
    generateOpenFile(static_cast<const OpenFileStmt&>(statement));
    break;
  case NodeKind::READ_FILE:
    generateReadFile(static_cast<const ReadFileStmt&>(statement));
    break;
  case NodeKind::WRITE_FILE:
    generateWriteFile(static_cast<const WriteFileStmt&>(statement));
    break;
  case NodeKind::CLOSE_FILE:
    generateCloseFile(static_cast<const CloseFileStmt&>(statement));
    break;
  default:
    throw std::logic_error("unsupported statement node");
  }
}

void CodeGenerator::generateVariableDeclaration(const VariableDeclarationStmt& statement)
{
  line(pythonName(statement.name) + " = " + defaultValue(statement.type));

  Symbol symbol;
  symbol.type = statement.type;
  declare(statement.name, std::move(symbol));
}

void CodeGenerator::generateConstantDeclaration(const ConstantDeclarationStmt& statement)
{
  line(pythonName(statement.name) + " = " + generateExpression(*statement.value));
}

void CodeGenerator::generateArrayDeclaration(const ArrayDeclarationStmt& statement)
{
  const std::string name = pythonName(statement.name);

  Symbol symbol;
  symbol.type = statement.elementType;
  symbol.isArray = true;

  const auto pendingIt = pendingArrays_.find(&statement);
  const PendingArray* pending = pendingIt == pendingArrays_.end() ? nullptr : &pendingIt->second;

  std::vector<std::string> lowerBounds;
  std::vector<std::string> upperBounds;
  lowerBounds.reserve(statement.dimensions.size());
  upperBounds.reserve(statement.dimensions.size());

  for (std::size_t i = 0; i < statement.dimensions.size(); ++i)
  {
    const ArrayDimension& dimension = statement.dimensions[i];
    const std::string lower = generateExpression(*dimension.lower);
    const std::string upper = generateExpression(*dimension.upper);

    ArrayBound bound;
    bound.expression = dimension.lower.get();

    std::int64_t lowerValue = 0;
    if (!foldInteger(*dimension.lower, lowerValue))
    {
      if (pending != nullptr && i < pending->lowerCaptures.size() &&
          !pending->lowerCaptures[i].empty())
        bound.capture = pending->lowerCaptures[i];
      else
        bound.capture = freshName("_cie_lower_" + name + "_");

      line(bound.capture + " = " + lower);
      lowerBounds.push_back(bound.capture);
    }
    else
    {
      lowerBounds.push_back(lower);
    }

    std::int64_t upperValue = 0;
    if (!foldInteger(*dimension.upper, upperValue))
    {
      const std::string capture = freshName("_cie_upper_" + name + "_");
      line(capture + " = " + upper);
      upperBounds.push_back(capture);
    }
    else
    {
      upperBounds.push_back(upper);
    }

    symbol.lowerBounds.push_back(std::move(bound));
  }

  if (pendingIt != pendingArrays_.end())
    pendingArrays_.erase(pendingIt);

  line(name + " = " + arrayInitializer(statement, lowerBounds, upperBounds));
  declare(statement.name, std::move(symbol));
}

void CodeGenerator::generateAssignment(const AssignmentStmt& statement)
{
  generateAssignmentTo(*statement.target, generateExpression(*statement.value));
}

void CodeGenerator::generateAssignmentTo(const LValueExpr& target, const std::string& value)
{
  line(generateExpression(target) + " = " + value);
}

void CodeGenerator::generateInput(const InputStmt& statement)
{
  for (const LValuePtr& target : statement.targets)
    generateAssignmentTo(*target, inputExpression(targetType(*target)));
}

void CodeGenerator::generateOutput(const OutputStmt& statement)
{
  if (statement.values.empty())
  {
    line("print()");
    return;
  }

  usesText_ = true;
  line("_cie_print(" + generateArguments(statement.values) + ")");
}

void CodeGenerator::generateIf(const IfStmt& statement)
{
  line("if " + generateExpression(*statement.condition) + ":");
  generateBlock(statement.thenBody);

  if (!statement.elseBody.empty())
  {
    line("else:");
    generateBlock(statement.elseBody);
  }
}

void CodeGenerator::generateCase(const CaseStmt& statement)
{
  const std::string selector = freshName("_cie_case_");
  line(selector + " = " + generateExpression(*statement.selector));

  if (statement.clauses.empty())
  {
    if (!statement.otherwiseBody.empty())
      generateStatements(statement.otherwiseBody);
    return;
  }

  for (std::size_t i = 0; i < statement.clauses.size(); ++i)
  {
    const CaseClause& clause = statement.clauses[i];
    const std::string keyword = i == 0 ? "if " : "elif ";
    line(keyword + selector + " == " + generateExpression(*clause.value) + ":");
    generateBlock(clause.body);
  }

  if (!statement.otherwiseBody.empty())
  {
    line("else:");
    generateBlock(statement.otherwiseBody);
  }
}

void CodeGenerator::generateFor(const ForStmt& statement)
{
  line("for " + pythonName(statement.variable) + " in " + rangeExpression(statement) + ":");
  generateBlock(statement.body);
}

void CodeGenerator::generateWhile(const WhileStmt& statement)
{
  line("while " + generateExpression(*statement.condition) + ":");
  generateBlock(statement.body);
}

void CodeGenerator::generateRepeat(const RepeatStmt& statement)
{
  line("while True:");
  ++indent_;
  if (statement.body.empty())
    line("pass");
  else
    generateStatements(statement.body);

  line("if " + generateExpression(*statement.condition) + ":");
  ++indent_;
  line("break");
  --indent_;
  --indent_;
}

void CodeGenerator::generateProcedure(const ProcedureDeclarationStmt& statement)
{
  generateSubprogram(statement.name, statement.parameters, statement.body);
}

void CodeGenerator::generateFunction(const FunctionDeclarationStmt& statement)
{
  generateSubprogram(statement.name, statement.parameters, statement.body);
}

void CodeGenerator::generateSubprogram(const std::string& name,
                                       const std::vector<Parameter>& parameters,
                                       const std::vector<StmtPtr>& body)
{
  const std::string pythonFunctionName = pythonName(name);

  std::unordered_set<std::string> assigned;
  std::unordered_set<std::string> locals;
  for (const Parameter& parameter : parameters)
    locals.insert(toLower(parameter.name));
  collectAssignments(body, assigned, locals);

  pushScope();

  std::string parameterList;
  for (std::size_t i = 0; i < parameters.size(); ++i)
  {
    const Parameter& parameter = parameters[i];
    if (i > 0)
      parameterList += ", ";
    parameterList += pythonName(parameter.name);

    Symbol symbol;
    symbol.type = parameter.type;
    declare(parameter.name, std::move(symbol));
  }

  line("def " + pythonFunctionName + "(" + parameterList + "):");
  ++indent_;
  emitGlobalDeclaration(assigned, locals);
  --indent_;
  generateBlock(body);
  popScope();
}

void CodeGenerator::collectAssignments(const std::vector<StmtPtr>& statements,
                                       std::unordered_set<std::string>& assigned,
                                       std::unordered_set<std::string>& locals) const
{
  for (const StmtPtr& statementPtr : statements)
  {
    const Stmt& statement = *statementPtr;
    switch (statement.kind)
    {
    case NodeKind::VARIABLE_DECLARATION:
      locals.insert(toLower(static_cast<const VariableDeclarationStmt&>(statement).name));
      break;
    case NodeKind::CONSTANT_DECLARATION:
      locals.insert(toLower(static_cast<const ConstantDeclarationStmt&>(statement).name));
      break;
    case NodeKind::ARRAY_DECLARATION:
      locals.insert(toLower(static_cast<const ArrayDeclarationStmt&>(statement).name));
      break;
    case NodeKind::ASSIGNMENT:
    {
      const auto& assignment = static_cast<const AssignmentStmt&>(statement);
      if (assignment.target->kind == NodeKind::VARIABLE)
        assigned.insert(toLower(static_cast<const VariableExpr&>(*assignment.target).name));
      break;
    }
    case NodeKind::INPUT:
      for (const LValuePtr& target : static_cast<const InputStmt&>(statement).targets)
      {
        if (target->kind == NodeKind::VARIABLE)
          assigned.insert(toLower(static_cast<const VariableExpr&>(*target).name));
      }
      break;
    case NodeKind::READ_FILE:
    {
      const auto& readFile = static_cast<const ReadFileStmt&>(statement);
      if (readFile.target->kind == NodeKind::VARIABLE)
        assigned.insert(toLower(static_cast<const VariableExpr&>(*readFile.target).name));
      break;
    }
    case NodeKind::FOR:
    {
      const auto& loop = static_cast<const ForStmt&>(statement);
      assigned.insert(toLower(loop.variable));
      collectAssignments(loop.body, assigned, locals);
      break;
    }
    case NodeKind::IF:
      collectAssignments(static_cast<const IfStmt&>(statement).thenBody, assigned, locals);
      collectAssignments(static_cast<const IfStmt&>(statement).elseBody, assigned, locals);
      break;
    case NodeKind::CASE:
    {
      const auto& caseStatement = static_cast<const CaseStmt&>(statement);
      for (const CaseClause& clause : caseStatement.clauses)
        collectAssignments(clause.body, assigned, locals);
      collectAssignments(caseStatement.otherwiseBody, assigned, locals);
      break;
    }
    case NodeKind::WHILE:
      collectAssignments(static_cast<const WhileStmt&>(statement).body, assigned, locals);
      break;
    case NodeKind::REPEAT:
      collectAssignments(static_cast<const RepeatStmt&>(statement).body, assigned, locals);
      break;
    default:
      break;
    }
  }
}

void CodeGenerator::emitGlobalDeclaration(const std::unordered_set<std::string>& assigned,
                                          const std::unordered_set<std::string>& locals)
{
  std::vector<std::string> names;
  for (const std::string& key : assigned)
  {
    if (locals.contains(key))
      continue;
    if (!scopes_.front().contains(key))
      continue;
    names.push_back(pythonName(key));
  }

  if (names.empty())
    return;

  std::sort(names.begin(), names.end());

  std::string list;
  for (std::size_t i = 0; i < names.size(); ++i)
  {
    if (i > 0)
      list += ", ";
    list += names[i];
  }

  line("global " + list);
}

void CodeGenerator::generateCall(const CallStmt& statement)
{
  line(pythonName(statement.name) + "(" + generateArguments(statement.arguments) + ")");
}

void CodeGenerator::generateReturn(const ReturnStmt& statement)
{
  if (statement.value)
    line("return " + generateExpression(*statement.value));
  else
    line("return");
}

void CodeGenerator::generateOpenFile(const OpenFileStmt& statement)
{
  usesFiles_ = true;
  const std::string path = freshName("_cie_file_");
  const std::string mode = statement.mode == FileMode::READ ? "r" : "w";
  line(path + " = " + generateExpression(*statement.fileName));
  line("_cie_files[" + path + "] = open(" + path + ", \"" + mode + "\")");
}

void CodeGenerator::generateReadFile(const ReadFileStmt& statement)
{
  usesFiles_ = true;
  const std::string key = generateExpression(*statement.fileName);
  const std::string stream = "_cie_files[" + key + "]";
  generateAssignmentTo(*statement.target, readExpression(stream, targetType(*statement.target)));
}

void CodeGenerator::generateWriteFile(const WriteFileStmt& statement)
{
  usesFiles_ = true;
  usesText_ = true;
  const std::string key = generateExpression(*statement.fileName);
  line("_cie_files[" + key + "].write(_cie_text(" + generateExpression(*statement.value) +
       ") + \"\\n\")");
}

void CodeGenerator::generateCloseFile(const CloseFileStmt& statement)
{
  usesFiles_ = true;
  const std::string key = generateExpression(*statement.fileName);
  line("_cie_files[" + key + "].close()");
  line("del _cie_files[" + key + "]");
}

