void CodeGenerator::line(const std::string& text)
{
  body_ << std::string(static_cast<std::size_t>(indent_) * 4, ' ') << text << '\n';
}

void CodeGenerator::blankLine()
{
  body_ << '\n';
}

std::string CodeGenerator::defaultValue(DataType type) const
{
  switch (type)
  {
  case DataType::INTEGER:
    return "0";
  case DataType::REAL:
    return "0.0";
  case DataType::CHAR:
  case DataType::STRING:
    return "\"\"";
  case DataType::BOOLEAN:
    return "False";
  }

  return "None";
}

DataType CodeGenerator::targetType(const LValueExpr& target) const
{
  switch (target.kind)
  {
  case NodeKind::VARIABLE:
  {
    const auto& variable = static_cast<const VariableExpr&>(target);
    const Symbol* symbol = lookup(variable.name);
    return symbol != nullptr ? symbol->type : DataType::STRING;
  }
  case NodeKind::ARRAY_ACCESS:
  {
    const auto& access = static_cast<const ArrayAccessExpr&>(target);
    const Symbol* symbol = lookup(access.name);
    if (symbol != nullptr && symbol->isArray)
      return symbol->type;
    return DataType::STRING;
  }
  default:
    return DataType::STRING;
  }
}

std::string CodeGenerator::inputExpression(DataType type)
{
  switch (type)
  {
  case DataType::INTEGER:
    return "int(input())";
  case DataType::REAL:
    return "float(input())";
  case DataType::CHAR:
    usesChar_ = true;
    return "_cie_char(input())";
  case DataType::BOOLEAN:
    return "input().strip().upper() == \"TRUE\"";
  case DataType::STRING:
    return "input()";
  }

  return "input()";
}

std::string CodeGenerator::readExpression(const std::string& stream, DataType type)
{
  switch (type)
  {
  case DataType::INTEGER:
    return "int(" + stream + ".readline())";
  case DataType::REAL:
    return "float(" + stream + ".readline())";
  case DataType::CHAR:
    usesChar_ = true;
    return "_cie_char(" + stream + ".readline().rstrip(\"\\r\\n\"))";
  case DataType::BOOLEAN:
    return stream + ".readline().strip().upper() == \"TRUE\"";
  case DataType::STRING:
    return stream + ".readline().rstrip(\"\\r\\n\")";
  }

  return stream + ".readline().rstrip(\"\\r\\n\")";
}

std::string CodeGenerator::arrayIndex(const Expr& index, const ArrayBound& lowerBound)
{
  const std::string indexText = generateExpression(index);

  if (!lowerBound.capture.empty())
  {
    if (precedenceOf(index) < PRECEDENCE_ADDITIVE)
      return "(" + indexText + ") - " + lowerBound.capture;
    return indexText + " - " + lowerBound.capture;
  }

  if (lowerBound.expression == nullptr)
    return indexText;

  std::int64_t lowerValue = 0;
  if (!foldInteger(*lowerBound.expression, lowerValue))
  {
    const std::string lowerText = generateExpression(*lowerBound.expression);
    return "(" + indexText + ") - (" + lowerText + ")";
  }

  std::int64_t indexValue = 0;
  if (foldInteger(index, indexValue))
    return std::to_string(indexValue - lowerValue);

  if (lowerValue == 0)
    return indexText;

  // Fold a constant term into the offset so that common loop indices such as
  // "b + 1" in an array declared as [1:n] become just "b".
  if (index.kind == NodeKind::BINARY)
  {
    const BinaryExpr& binary = static_cast<const BinaryExpr&>(index);
    if (binary.op == BinaryOp::ADD || binary.op == BinaryOp::SUBTRACT)
    {
      std::int64_t rightValue = 0;
      if (foldInteger(*binary.right, rightValue))
      {
        const std::int64_t term = binary.op == BinaryOp::ADD ? rightValue : -rightValue;
        const std::int64_t offset = term - lowerValue;
        const std::string left = generateExpression(*binary.left, PRECEDENCE_ADDITIVE);
        if (offset == 0)
          return left;
        if (offset > 0)
          return left + " + " + std::to_string(offset);
        return left + " - " + std::to_string(-offset);
      }

      std::int64_t leftValue = 0;
      if (binary.op == BinaryOp::ADD && foldInteger(*binary.left, leftValue))
      {
        const std::int64_t offset = leftValue - lowerValue;
        const std::string right = generateExpression(*binary.right, PRECEDENCE_ADDITIVE);
        if (offset == 0)
          return right;
        if (offset > 0)
          return right + " + " + std::to_string(offset);
        return right + " - " + std::to_string(-offset);
      }
    }
  }

  if (lowerValue < 0)
  {
    const std::string offset = std::to_string(-lowerValue);
    if (precedenceOf(index) < PRECEDENCE_ADDITIVE)
      return "(" + indexText + ") + " + offset;
    return indexText + " + " + offset;
  }

  const std::string offset = std::to_string(lowerValue);
  if (precedenceOf(index) < PRECEDENCE_ADDITIVE)
    return "(" + indexText + ") - " + offset;
  return indexText + " - " + offset;
}

std::string CodeGenerator::arrayInitializer(const ArrayDeclarationStmt& statement,
                                            const std::vector<std::string>& lowerBounds,
                                            const std::vector<std::string>& upperBounds)
{
  if (statement.dimensions.empty())
    return "[]";

  std::string initializer = defaultValue(statement.elementType);

  for (std::size_t i = statement.dimensions.size(); i-- > 0;)
  {
    const ArrayDimension& dimension = statement.dimensions[i];
    const std::string& lower = lowerBounds.at(i);
    const std::string& upper = upperBounds.at(i);

    std::int64_t lowerValue = 0;
    std::int64_t upperValue = 0;
    const bool lowerIsLiteral = foldInteger(*dimension.lower, lowerValue);
    const bool upperIsLiteral = foldInteger(*dimension.upper, upperValue);

    std::string range;
    if (lowerIsLiteral && upperIsLiteral)
    {
      if (lowerValue == 0)
        range = "range(" + std::to_string(upperValue + 1) + ")";
      else
        range = "range(" + std::to_string(lowerValue) + ", " + std::to_string(upperValue + 1) + ")";
    }
    else if (lowerIsLiteral && lowerValue == 0)
    {
      range = "range(" + upper + " + 1)";
    }
    else
    {
      range = "range(" + lower + ", " + upper + " + 1)";
    }

    initializer = "[" + initializer + " for _ in " + range + "]";
  }

  return initializer;
}

std::string CodeGenerator::rangeExpression(const ForStmt& statement)
{
  const std::string start = generateExpression(*statement.start);
  const std::string end = generateExpression(*statement.end);

  if (!statement.step)
    return "range(" + start + ", " + end + " + 1)";

  const std::string step = generateExpression(*statement.step);
  std::int64_t stepValue = 0;
  if (foldInteger(*statement.step, stepValue))
  {
    if (stepValue == 1)
      return "range(" + start + ", " + end + " + 1)";
    if (stepValue > 1)
      return "range(" + start + ", " + end + " + 1, " + step + ")";
    if (stepValue < 0)
      return "range(" + start + ", " + end + " - 1, " + step + ")";
  }

  usesDynamicRange_ = true;
  return "_cie_range(" + start + ", " + end + ", " + step + ")";
}

bool CodeGenerator::foldInteger(const Expr& expression, std::int64_t& value) const
{
  if (expression.kind == NodeKind::INTEGER_LITERAL)
  {
    value = static_cast<const IntegerLiteralExpr&>(expression).value;
    return true;
  }

  if (expression.kind == NodeKind::UNARY)
  {
    const UnaryExpr& unary = static_cast<const UnaryExpr&>(expression);
    if (unary.op != UnaryOp::NEGATE)
      return false;

    std::int64_t operand = 0;
    if (!foldInteger(*unary.operand, operand))
      return false;

    value = -operand;
    return true;
  }

  return false;
}

void CodeGenerator::emitPreamble(std::ostringstream& document) const
{
  bool needsSeparator = false;
  const auto separate = [&document, &needsSeparator]()
  {
    if (needsSeparator)
      document << '\n';
    needsSeparator = true;
  };

  if (usesRandom_)
  {
    document << "import random\n";
    needsSeparator = true;
  }

  if (usesRound_)
  {
    document << "import decimal\n";
    needsSeparator = true;
  }

  if (usesFiles_)
  {
    separate();
    document << "_cie_files = {}\n";
  }

  if (usesText_)
  {
    separate();
    document << "def _cie_text(value):\n"
                "    if value is True:\n"
                "        return \"TRUE\"\n"
                "    if value is False:\n"
                "        return \"FALSE\"\n"
                "    return str(value)\n"
                "\n"
                "def _cie_print(*values):\n"
                "    print(\"\".join(_cie_text(value) for value in values))\n";
  }

  if (usesChar_)
  {
    separate();
    document << "def _cie_char(text):\n"
                "    if len(text) == 0:\n"
                "        raise ValueError(\"expected a character, got an empty string\")\n"
                "    return text[0]\n";
  }

  if (usesRandom_)
  {
    separate();
    document << "def _cie_random(n=None):\n"
                "    if n is None:\n"
                "        return random.uniform(0, 1)\n"
                "    return random.randrange(n)\n";
  }

  if (usesSubstring_)
  {
    separate();
    document << "def _cie_substring(value, start, length):\n"
                "    return value[start - 1:start - 1 + length]\n";
  }

  if (usesDiv_ || usesMod_)
  {
    separate();
    document << "def _cie_div(a, b):\n"
                "    quotient = abs(a) // abs(b)\n"
                "    if (a < 0) != (b < 0):\n"
                "        return -quotient\n"
                "    return quotient\n";
  }

  if (usesMod_)
  {
    separate();
    document << "def _cie_mod(a, b):\n"
                "    return a - _cie_div(a, b) * b\n";
  }

  if (usesRound_)
  {
    separate();
    document << "def _cie_round(value, places=0):\n"
                "    quantum = decimal.Decimal(1).scaleb(-places)\n"
                "    rounded = decimal.Decimal(str(value)).quantize(quantum, "
                "rounding=decimal.ROUND_HALF_UP)\n"
                "    if places <= 0:\n"
                "        return int(rounded)\n"
                "    return float(rounded)\n";
  }

  if (usesDynamicRange_)
  {
    separate();
    document << "def _cie_range(start, end, step):\n"
                "    if step > 0:\n"
                "        return range(start, end + 1, step)\n"
                "    return range(start, end - 1, step)\n";
  }
}
