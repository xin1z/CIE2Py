std::string CodeGenerator::generateExpression(const Expr& expression, int minimumPrecedence)
{
  const int precedence = precedenceOf(expression);
  std::string text;

  switch (expression.kind)
  {
  case NodeKind::INTEGER_LITERAL:
    text = std::to_string(static_cast<const IntegerLiteralExpr&>(expression).value);
    break;
  case NodeKind::REAL_LITERAL:
  {
    const auto& real = static_cast<const RealLiteralExpr&>(expression);
    text = real.text.empty() ? literal::formatReal(real.value) : real.text;
    break;
  }
  case NodeKind::BOOLEAN_LITERAL:
    text = static_cast<const BooleanLiteralExpr&>(expression).value ? "True" : "False";
    break;
  case NodeKind::CHAR_LITERAL:
    text = literal::quoteChar(static_cast<const CharLiteralExpr&>(expression).value);
    break;
  case NodeKind::STRING_LITERAL:
    text = literal::quoteString(static_cast<const StringLiteralExpr&>(expression).value);
    break;
  case NodeKind::VARIABLE:
    text = pythonName(static_cast<const VariableExpr&>(expression).name);
    break;
  case NodeKind::ARRAY_ACCESS:
    text = generateArrayAccess(static_cast<const ArrayAccessExpr&>(expression));
    break;
  case NodeKind::UNARY:
  {
    const UnaryExpr& unary = static_cast<const UnaryExpr&>(expression);
    if (unary.op == UnaryOp::NEGATE)
      text = "-" + generateExpression(*unary.operand, PRECEDENCE_UNARY);
    else
      text = "not " + generateExpression(*unary.operand, PRECEDENCE_NOT);
    break;
  }
  case NodeKind::BINARY:
  {
    const BinaryExpr& binary = static_cast<const BinaryExpr&>(expression);
    const char* op = "+";
    const char* helper = nullptr;
    int leftPrecedence = PRECEDENCE_ADDITIVE;
    int rightPrecedence = PRECEDENCE_MULTIPLICATIVE;

    switch (binary.op)
    {
    case BinaryOp::ADD:
      op = "+";
      leftPrecedence = PRECEDENCE_ADDITIVE;
      rightPrecedence = PRECEDENCE_MULTIPLICATIVE;
      break;
    case BinaryOp::SUBTRACT:
      op = "-";
      leftPrecedence = PRECEDENCE_ADDITIVE;
      rightPrecedence = PRECEDENCE_MULTIPLICATIVE;
      break;
    case BinaryOp::MULTIPLY:
      op = "*";
      leftPrecedence = PRECEDENCE_MULTIPLICATIVE;
      rightPrecedence = PRECEDENCE_UNARY;
      break;
    case BinaryOp::DIVIDE:
      op = "/";
      leftPrecedence = PRECEDENCE_MULTIPLICATIVE;
      rightPrecedence = PRECEDENCE_UNARY;
      break;
    case BinaryOp::DIV:
      usesDiv_ = true;
      helper = "_cie_div";
      break;
    case BinaryOp::MOD:
      usesMod_ = true;
      helper = "_cie_mod";
      break;
    case BinaryOp::POWER:
      op = "**";
      // Python's ** is right-associative, so a power on the left needs
      // parentheses while a power on the right does not.
      leftPrecedence = PRECEDENCE_POWER + 1;
      rightPrecedence = PRECEDENCE_POWER;
      break;
    case BinaryOp::EQUAL:
      op = "==";
      leftPrecedence = PRECEDENCE_ADDITIVE;
      rightPrecedence = PRECEDENCE_ADDITIVE;
      break;
    case BinaryOp::NOT_EQUAL:
      op = "!=";
      leftPrecedence = PRECEDENCE_ADDITIVE;
      rightPrecedence = PRECEDENCE_ADDITIVE;
      break;
    case BinaryOp::LESS:
      op = "<";
      leftPrecedence = PRECEDENCE_ADDITIVE;
      rightPrecedence = PRECEDENCE_ADDITIVE;
      break;
    case BinaryOp::LESS_EQUAL:
      op = "<=";
      leftPrecedence = PRECEDENCE_ADDITIVE;
      rightPrecedence = PRECEDENCE_ADDITIVE;
      break;
    case BinaryOp::GREATER:
      op = ">";
      leftPrecedence = PRECEDENCE_ADDITIVE;
      rightPrecedence = PRECEDENCE_ADDITIVE;
      break;
    case BinaryOp::GREATER_EQUAL:
      op = ">=";
      leftPrecedence = PRECEDENCE_ADDITIVE;
      rightPrecedence = PRECEDENCE_ADDITIVE;
      break;
    case BinaryOp::AND:
      op = "and";
      leftPrecedence = PRECEDENCE_AND;
      rightPrecedence = PRECEDENCE_NOT;
      break;
    case BinaryOp::OR:
      op = "or";
      leftPrecedence = PRECEDENCE_OR;
      rightPrecedence = PRECEDENCE_AND;
      break;
    }

    if (helper != nullptr)
    {
      text = std::string(helper) + "(" + generateExpression(*binary.left) + ", " +
             generateExpression(*binary.right) + ")";
    }
    else
    {
      text = generateExpression(*binary.left, leftPrecedence) + " " + op + " " +
             generateExpression(*binary.right, rightPrecedence);
    }
    break;
  }
  case NodeKind::FUNCTION_CALL:
    text = generateBuiltinCall(static_cast<const FunctionCallExpr&>(expression));
    break;
  default:
    throw std::logic_error("unsupported expression node");
  }

  if (precedence < minimumPrecedence)
    return "(" + text + ")";
  return text;
}

int CodeGenerator::precedenceOf(const Expr& expression) const
{
  switch (expression.kind)
  {
  case NodeKind::UNARY:
    return static_cast<const UnaryExpr&>(expression).op == UnaryOp::NOT ? PRECEDENCE_NOT
                                                                        : PRECEDENCE_UNARY;
  case NodeKind::BINARY:
    switch (static_cast<const BinaryExpr&>(expression).op)
    {
    case BinaryOp::OR:
      return PRECEDENCE_OR;
    case BinaryOp::AND:
      return PRECEDENCE_AND;
    case BinaryOp::EQUAL:
    case BinaryOp::NOT_EQUAL:
    case BinaryOp::LESS:
    case BinaryOp::LESS_EQUAL:
    case BinaryOp::GREATER:
    case BinaryOp::GREATER_EQUAL:
      return PRECEDENCE_COMPARISON;
    case BinaryOp::ADD:
    case BinaryOp::SUBTRACT:
      return PRECEDENCE_ADDITIVE;
    case BinaryOp::MULTIPLY:
    case BinaryOp::DIVIDE:
      return PRECEDENCE_MULTIPLICATIVE;
    case BinaryOp::DIV:
    case BinaryOp::MOD:
      // These are emitted as calls to helper functions.
      return PRECEDENCE_PRIMARY;
    case BinaryOp::POWER:
      return PRECEDENCE_POWER;
    }
    return PRECEDENCE_PRIMARY;
  default:
    return PRECEDENCE_PRIMARY;
  }
}

std::string CodeGenerator::generateArguments(const std::vector<ExprPtr>& arguments)
{
  std::string result;
  for (std::size_t i = 0; i < arguments.size(); ++i)
  {
    if (i > 0)
      result += ", ";
    result += generateExpression(*arguments[i]);
  }
  return result;
}

std::string CodeGenerator::generateArrayAccess(const ArrayAccessExpr& access)
{
  const Symbol* symbol = lookup(access.name);
  std::string result = pythonName(access.name);

  for (std::size_t i = 0; i < access.indices.size(); ++i)
  {
    if (symbol != nullptr && symbol->isArray && i < symbol->lowerBounds.size())
      result += "[" + arrayIndex(*access.indices[i], symbol->lowerBounds[i]) + "]";
    else
      result += "[" + generateExpression(*access.indices[i]) + "]";
  }

  return result;
}

std::string CodeGenerator::generateBuiltinCall(const FunctionCallExpr& call)
{
  const std::string name = toLower(call.name);

  if (name == "div")
  {
    usesDiv_ = true;
    return "_cie_div(" + generateArguments(call.arguments) + ")";
  }
  if (name == "mod")
  {
    usesMod_ = true;
    return "_cie_mod(" + generateArguments(call.arguments) + ")";
  }
  if (name == "length")
    return "len(" + generateArguments(call.arguments) + ")";
  if (name == "lcase")
    return "str.lower(" + generateArguments(call.arguments) + ")";
  if (name == "ucase")
    return "str.upper(" + generateArguments(call.arguments) + ")";
  if (name == "substring")
  {
    usesSubstring_ = true;
    return "_cie_substring(" + generateArguments(call.arguments) + ")";
  }
  if (name == "round")
  {
    usesRound_ = true;
    return "_cie_round(" + generateArguments(call.arguments) + ")";
  }
  if (name == "random")
  {
    usesRandom_ = true;
    return "_cie_random(" + generateArguments(call.arguments) + ")";
  }

  return pythonName(call.name) + "(" + generateArguments(call.arguments) + ")";
}

